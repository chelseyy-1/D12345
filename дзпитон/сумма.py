# Чтение входных данных
n = int(input().strip())

# Вычисляем сумму
if n == 1:
    # Для n=1: числа от 1 до 9
    # Сумма = (1+9)*9/2 = 45
    total = 45
else:
    # Используем формулу: сумма = 9 * 10^(n-1) * (10^(n-1) * 11 - 1) // 2
    power = 10 ** (n - 1)
    total = 9 * power * (11 * power - 1) // 2

# Выводим результат (все цифры суммы)
print(total)